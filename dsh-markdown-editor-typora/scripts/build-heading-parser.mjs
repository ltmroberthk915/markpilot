// Build the server-side outline reader from the editor's pinned Markdown grammar.
// Pass the dsh-markpilot directory when its installed dependencies live in another checkout.
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const sources = process.argv[2] ? resolve(process.argv[2]) : fileURLToPath(new URL('../../dsh-markpilot/', import.meta.url));
const require = createRequire(join(sources, 'package.json'));
const { build } = require('esbuild');
const license = pkg => readFileSync(join(sources, 'node_modules', '@lezer', pkg, 'LICENSE'), 'utf8').trim();
await build({
  absWorkingDir: sources,
  stdin: { contents: "import {parser, GFM} from '@lezer/markdown'; export const headingParser = parser.configure(GFM);", resolveDir: sources },
  outfile: fileURLToPath(new URL('../lib/vendor/heading-parser.js', import.meta.url)),
  platform: 'node', format: 'esm', target: 'node20', bundle: true,
  banner: { js: '/* Generated by scripts/build-heading-parser.mjs.\n' + ['markdown', 'common', 'highlight'].map(pkg => '@lezer/' + pkg + '\n' + license(pkg)).join('\n\n') + '\n*/' },
});
