// Adapt upstream writing styles to Vditor, retaining the original CSS/license.
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../extension-src/render');
let output='/* Konayuki by Sidi Liu (MIT). Generated by tools/adapt_konayuki.cjs. */\n';
// T8 代码高亮对比度：上游 --syntax-* 按 Typora/CodeMirror 调色，走我们的 hljs 管线
// （themes.css 的 .hljs-keyword/string/comment/number 规则经 var() 消费这些值，
// .hljs 底色=var(--code-bg-color)：dark #24283b / light #f7f4ef）有两处缺口：
//  ① 低对比：dark --syntax-comment #526270 仅 2.32:1（R5 实测）；light 的
//     comment 3.55:1，string/number 4.55/4.58:1 贴线。下表只覆写不达标的值。
//  ② 缺 token：.hljs-title/.hljs-type/.hljs-class/.hljs-literal/.hljs-selector-tag
//     此前无作用域规则，落回 vditor 动态加载的 github(-dark) 主题色，随 CDN 摆动。
// 生成时补两层（覆写变量 + 补缺失 token），全部色值对代码底验过 ≥4.5:1（WCAG AA）。
const HLJS={
  light:{'--syntax-comment':'#75604f','--syntax-string':'#3f6a0a','--syntax-number':'#9a4207'},
  dark:{'--syntax-comment':'#8a9bb8'},
};
for(const name of ['light','dark']){
  const source=fs.readFileSync(path.join(root,'themes/konayuki/konayuki-'+name+'.css'),'utf8').replace(/\/\*[\s\S]*?\*\//g,'');
  const scope=':root[data-editor-theme="konayuki-'+name+'"]';
  let start=0,depth=0,opening=0;
  for(let i=0;i<source.length;i++){
    if(source[i]==='{'){if(!depth)opening=i;depth++;}
    else if(source[i]==='}' && --depth===0){
      const selectors=source.slice(start,opening).trim(),body=source.slice(opening+1,i);start=i+1;
      if(selectors===':root')output+=scope+'{'+body+'}\n';
      else if(!selectors.startsWith('@')){
        const selected=selectors.split(',').map(s=>s.trim()).filter(s=>s.startsWith('#write ')&&!s.includes(':has('));
        if(selected.length)output+=selected.map(s=>scope+' '+s.replaceAll('#write','.vditor-reset')).join(',\n')+'{'+body+'}\n';
      }
    }
  }
  output+=scope+'{\n'+Object.entries(HLJS[name]).map(([k,v])=>'    '+k+': '+v+';\n').join('')+'}\n';
  output+=scope+' .vditor-reset .hljs-selector-tag{color:var(--syntax-keyword);}\n'
    +scope+' .vditor-reset .hljs-literal,\n'
    +scope+' .vditor-reset .hljs-number{color:var(--syntax-number);}\n'
    +scope+' .vditor-reset .hljs-title,\n'
    +scope+' .vditor-reset .hljs-type,\n'
    +scope+' .vditor-reset .hljs-class{color:var(--syntax-variable-2);}\n';
}
fs.writeFileSync(path.join(root,'css/konayuki.css'),output);
console.log('Adapted Konayuki writing styles');
